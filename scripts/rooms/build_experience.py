"""Build the Experience room (CHANGES-2 "Опыт v2": archive table with dossier folders) with
the handoff's isometric helpers (scripts/rooms/scenes2.py, copied from handoff4/generators,
layout from build_exp.py) into client/src/experience/markup.ts.

Usage: python3 scripts/rooms/build_experience.py
"""
import json
import re
from pathlib import Path

from scenes2 import P, Sc, shell

COLORS = {"{{c1}}": "#EC4899", "{{c2}}": "#A855F7", "{{c3}}": "#3B82F6", "{{ink}}": "#C48BFA"}
K, TX, TY = 1.7, -261, -55  # same room placement as the main scene


def T(pt):  # room coordinates -> screen coordinates
    return (830 + (pt[0] - 830) * K + TX, 470 + (pt[1] - 470) * K + TY)


cols = ["{{c1}}", "{{c2}}", "{{c3}}"]


def fillc(i, op):
    return "fill:%s;fill-opacity:%s;" % (cols[i % 3], op)


# Archive table and wall panels
s = Sc(); s.d = 0.1
s.glow(5.4, 3.2)
s.box(0.9, 2.0, 0, 9.1, 3.7, .7, "t", "fill:rgba(168,85,247,.06);")
for i, x in enumerate([1.2, 2.5, 3.8, 5.1, 6.4, 7.7]):
    s.path([P(x, .3, 1.1), P(x + .9, .3, 1.1), P(x + .9, .3, 2.1), P(x, .3, 2.1)], "c", fillc(i, .14))
    s.line(P(x + .12, .3, 1.7), P(x + .7, .3, 1.7)); s.line(P(x + .12, .3, 1.45), P(x + .5, .3, 1.45))
objects = "\n".join(s.o)

# Dossier folders, one group each so they can lift; anchors for the leader lines
folders, anchors = [], []
for i, x in enumerate([1.5, 3.7, 5.9]):
    f = Sc(); f.d = 0.9 + i * .25
    f.box(x, 2.25, .7, x + .42, 3.45, 3.0, "t", fillc(i, .5))
    f.box(x, 2.25, 3.0, x + .42, 2.95, 3.34, "t", fillc(i, .8))
    for k in range(3):
        f.line(P(x + .42, 2.5, 1.2 + k * .5), P(x + .42, 3.2, 1.2 + k * .5))
    folders.append("\n".join(f.o))
    anchors.append(T(P(x + .21, 2.6, 3.34)))

# The empty dashed folder: "your product"
x = 8.1
fmt = lambda pts: "L".join("%.1f %.1f" % p for p in pts)
empty = '<path class="dsh2" d="M%sZ"/>' % fmt([P(x + .42, 2.25, .7), P(x + .42, 3.45, .7), P(x + .42, 3.45, 3.0), P(x + .42, 2.25, 3.0)])
empty += '<path class="dsh2" d="M%s"/>' % fmt([P(x, 3.45, 3.0), P(x + .42, 3.45, 3.0), P(x + .42, 2.25, 3.0)])
anchors.append(T(P(x + .42, 2.9, 3.0)))

# People and a data packet running along the table
pp = Sc(); pp.d = 1.6
pp.stand(1.0, 4.7, 0, 1); pp.stand(7.8, 4.9, 1, 0); pp.sit(4.4, 4.8, 0)
pp.bubble(1.0, 4.7, 1.25); pp.bubble(7.8, 4.9, 1.25, .9)
flow = Sc(); flow.d = 1.5
for a, b in [(P(1.9, 3.7, .7), P(4.1, 3.7, .7)), (P(4.1, 3.7, .7), P(6.3, 3.7, .7)), (P(6.3, 3.7, .7), P(8.3, 3.7, .7))]:
    flow.dash(a, b)
flow.packet([P(1.9, 3.7, .7), P(8.3, 3.7, .7)], 6, 0.2)

wall = '<text class="wn" transform="matrix(.866 .5 0 1 %.1f %.1f)" font-size="74">04</text>' % P(4.4, .3, 2.95)
SHELL = shell()
# Ghost rooms get a static copy of the shell (line-draw animations don't run inside <use>)
ghost_shell = re.sub(r'pathLength="1" class="dr ([a-z])" style="[^"]*"', r'class="gs \1"', SHELL)
ghosts = ""
for dy, op in [(-125, .34), (-250, .16), (125, .34), (250, .16)]:
    ghosts += '<g style="opacity:%s;transform:translate(0,%dpx);filter:blur(1.2px)">%s</g>' % (op, dy, ghost_shell)
for dx, dy, op in [(470, 270, .3), (-470, -270, .3), (-470, 270, .3), (470, -270, .3), (940, 540, .12), (-940, -540, .12), (0, 540, .14), (0, -540, .1)]:
    ghosts += '<g style="opacity:%s;transform:translate(%dpx,%dpx);filter:blur(1.6px)">%s</g>' % (op, dx, dy, ghost_shell)


def bake(text):
    for k, v in COLORS.items():
        text = text.replace(k, v)
    left = re.findall(r"\{\{[^}]+\}\}", text)
    if left:
        raise SystemExit(f"unresolved template vars: {set(left)}")
    return text


parts = {
    "SHELL": SHELL, "OBJECTS": objects, "EMPTY": empty, "FLOW": "\n".join(flow.o),
    "PEOPLE": "\n".join(pp.o), "WALL": wall, "GHOSTS": ghosts,
}
out = Path(__file__).resolve().parents[2] / "client/src/experience/markup.ts"
out.parent.mkdir(parents=True, exist_ok=True)
body = "// Generated by scripts/rooms/build_experience.py. Do not edit by hand.\n"
body += "".join(f"export const {k} = {json.dumps(bake(v), ensure_ascii=False)};\n" for k, v in parts.items())
body += f"export const FOLDERS: string[] = {json.dumps([bake(f) for f in folders], ensure_ascii=False)};\n"
body += "// Leader anchors on screen: three folders, then the empty folder\n"
body += f"export const ANCHORS: [number, number][] = {json.dumps([[round(a, 1), round(b, 1)] for a, b in anchors])};\n"
out.write_text(body, encoding="utf-8")
print(out, [[round(a), round(b)] for a, b in anchors])
