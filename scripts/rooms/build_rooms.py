"""Build extra ship rooms (not in the Claude Design mockups) with the handoff's isometric
helpers (scenes.py, copied from the handoff generators) into client/src/scene/roomsMarkup.ts.

Usage: python3 scripts/rooms/build_rooms.py

Per-item placeholders {{fcN}} / {{foN}} / {{soN}} (fill colour, fill opacity, selection frame)
are filled at render time, like the case gallery.
"""
import json
from pathlib import Path

from scenes import P, Sc, f

COLORS = {"{{c1}}": "#EC4899", "{{c2}}": "#A855F7", "{{c3}}": "#3B82F6", "{{ink}}": "#C48BFA"}


def item_style(n):
    return "fill:{{fc%d}};fill-opacity:{{fo%d}};" % (n, n)


def frame(s, pts, n):
    s.path(pts, "a", "opacity:{{so%d}};stroke-width:2.4;fill:none;" % n)


def experience():
    """Career deck: four rising pillars (2018 → 2025+) joined by a dashed trajectory."""
    s = Sc()
    s.shell()
    # Back-wall timeline rail with year ticks
    s.line(P(.3, .3, 1.0), P(9.6, .3, 1.0), "a")
    for x in (1.6, 3.8, 6.0, 8.2):
        s.line(P(x, .3, .8), P(x, .3, 1.2))
    # Pillars climb as a staircase towards the far corner, one per career step.
    pillars = [  # x, y, height, label
        (1.0, 4.2, .6, "2018 YANDEX"),
        (3.2, 3.2, 1.2, "2021 SBER"),
        (5.4, 2.2, 1.8, "2022 SAMOKAT"),
        (7.6, 1.2, 2.4, "2025 INDEPENDENT"),
    ]
    tops = []
    for n, (x, y0, h, label) in enumerate(pillars, start=1):
        x1, y1 = x + 1.3, y0 + 1.3
        s.box(x, y0, 0, x1, y1, h, "c", item_style(n))
        frame(s, [P(x, y0, h), P(x1, y0, h), P(x1, y1, h), P(x, y1, h)], n)
        tops.append(P(x + .65, y0 + .65, h))
        s.text(x + .65, y1 + .6, 0, label, 8.5)
    for a, b in zip(tops, tops[1:]):
        s.dash(a, b)
    # Small holo-sphere on the bridge
    s.disc(2.0, 1.6, 0, .8, .2, "c", "fill:{{c3}};fill-opacity:.35;")
    s.sphere(2.0, 1.6, .9, .45, "g")
    for pts, dur, begin in [
        ([(3, 6.6, 0), (9.5, 6.6, 0)], 16, 2),
        ([(5.0, 5.3, 0), (9.4, 5.3, 0)], 11, 3),
    ]:
        s.person(pts, dur, begin)
    s.raw('<rect class="cut" x="590" y="250" width="560" height="3" fill="url(#lgc)"/>')
    out = "\n".join(s.o)
    for k, v in COLORS.items():
        out = out.replace(k, v)
    return out


if __name__ == "__main__":
    target = Path(__file__).resolve().parents[2] / "client/src/scene/roomsMarkup.ts"
    body = "// Generated by scripts/rooms/build_rooms.py. Do not edit by hand.\n"
    body += "// Career deck; {{fcN}} {{foN}} {{soN}} are per-pillar placeholders (N = 1–4)\n"
    body += f"export const EXPERIENCE = {json.dumps(experience(), ensure_ascii=False)};\n"
    target.write_text(body, encoding="utf-8")
    print(target)
