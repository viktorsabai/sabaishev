"""Extract hero ship SVG fragments from the Claude Design mockup (Main.dc.html)
into client/src/scene/shipMarkup.ts. Template colors are baked in.

Usage: python3 -I scripts/extract-ship.py path/to/Main.dc.html path/to/Cases.dc.html
"""
import json, re, sys
from pathlib import Path

C = {"{{c1}}": "#EC4899", "{{c2}}": "#A855F7", "{{c3}}": "#3B82F6", "{{ink}}": "#C48BFA"}

def load(path):
    text = Path(path).read_text(encoding="utf-8")
    for k, v in C.items():
        text = text.replace(k, v)
    return text


src = load(sys.argv[1])
cases_src = load(sys.argv[2])


def between(start, end, text=src):
    i = text.index(start) + len(start)
    return text[i:text.index(end, i)].strip()


stars_svg = between('<svg aria-hidden="true" width="1440" height="900" viewBox="0 0 1440 900" style="position:absolute;inset:0;pointer-events:none" fill="none">', "</svg>")
ship_svg = between('aria-label="Чертёж многоуровневого космического корабля — продукта"', "<sc-if")
defs = between("<defs>", "</defs>", ship_svg)
grid = between('<g class="gmv">', "</g></g></g>", ship_svg)
ship = between('<g class="shipg">', "<sc-for", ship_svg)
ship = ship[: ship.rindex("</g>")].strip()
leads = between('transition:opacity .5s ease">', "</g>", ship_svg)

# Deck cutaways: one <sc-if value="{{sN}}"> block per stage; keep the inner SVG content.
scenes = []
for n in range(1, 9):
    block = between(f'<sc-if value="{{{{s{n}}}}}"', "</sc-if>")
    svg_open = block.index("<svg")
    scenes.append(between(">", "</svg>", block[block.index(">", svg_open):]))

# Case gallery room. Per-panel {{fcN}}/{{foN}}/{{soN}} (fill, fill opacity, selection frame)
# stay as placeholders and are filled at render time.
gallery = between('aria-label="Галерея проектов внутри корабля"', "</svg>", cases_src)
gallery = gallery[gallery.index(">") + 1:].strip()

leftover = re.findall(r"\{\{[^}]+\}\}", stars_svg + defs + grid + ship + leads + "".join(scenes))
leftover += [v for v in re.findall(r"\{\{[^}]+\}\}", gallery) if not re.fullmatch(r"\{\{(fc|fo|so)[1-6]\}\}", v)]
if leftover:
    sys.exit(f"unresolved template vars: {set(leftover)}")

out = Path(__file__).resolve().parent.parent / "client/src/scene/shipMarkup.ts"
parts = {"STARS": stars_svg, "DEFS": defs, "GRID": grid, "SHIP": ship, "LEADS": leads}
body = "// Generated by scripts/extract-ship.py from the Claude Design mockup. Do not edit by hand.\n"
body += "".join(f"export const {k} = {json.dumps(v, ensure_ascii=False)};\n" for k, v in parts.items())
body += "// Deck cutaway for stages 01–08 (index 0–7)\n"
body += f"export const SCENES = {json.dumps(scenes, ensure_ascii=False, indent=0)};\n"
body += "// Case gallery; {{fcN}} {{foN}} {{soN}} are per-panel placeholders (N = 1–6)\n"
body += f"export const GALLERY = {json.dumps(gallery, ensure_ascii=False)};\n"
parts["SCENES"] = "".join(scenes)
parts["GALLERY"] = gallery
out.write_text(body, encoding="utf-8")
print(out, {k: len(v) for k, v in parts.items()})
