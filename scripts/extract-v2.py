"""Extract the v2 main scene (CHANGES-2 handoff) from reference/Main.dc.html into
client/src/scene/v2/markup.ts: ship, star streaks, grid, leads, and per stage the ghost
rooms, the room itself, leader lines and the order/position of the deliverable cards.
Texts are not extracted — they live in scene/v2/content.ts (ru/en/th).

Usage: python3 -I scripts/extract-v2.py path/to/handoff2/reference/Main.dc.html
"""
import json, re, sys
from pathlib import Path

C = {"{{c1}}": "#EC4899", "{{c2}}": "#A855F7", "{{c3}}": "#3B82F6", "{{ink}}": "#C48BFA"}
src = Path(sys.argv[1]).read_text(encoding="utf-8")
for k, v in C.items():
    src = src.replace(k, v)


def between(start, end, text=src):
    i = text.index(start) + len(start)
    return text[i:text.index(end, i)].strip()


stars = between('<svg aria-hidden="true" width="1440" height="900" viewBox="0 0 1440 900" style="position:absolute;inset:0;pointer-events:none" fill="none">', "</svg>")
ship_svg = between('aria-label="Чертёж многоуровневого космического корабля — продукта"', "<sc-if")
defs = between("<defs>", "</defs>", ship_svg)
grid = between('<g class="gmv">', "</g></g></g>", ship_svg)
ship = between('<g class="shipg">', '<g style="opacity:{{leadOp}}', ship_svg)
ship = ship[: ship.rindex("</g>")].strip()
leads = between('<g style="opacity:{{leadOp}};transition:opacity .5s ease">', "</g>", ship_svg)

# Ghost rooms reference #shellg via <use>; styles and line-draw animations don't reach
# <use> instances reliably, so ghosts get a static inline copy of the shell instead.
shell = between('<g id="shellg">', "</g>", defs)
ghost_shell = re.sub(r'pathLength="1" class="dr ([a-z])" style="[^"]*"', r'class="gs \1"', shell)

rooms = []
room_transform = None
card_re = re.compile(r'<div class="cc" tabindex="0" style="top:(\d+)px;animation:sin \.7s ease ([\d.]+)s both">.*?<span class="mono" style="[^"]*">(\d\d)</span>')
for n in range(1, 9):
    block = between(f'<sc-if value="{{{{s{n}}}}}"', "</sc-if>")
    t = re.search(r"transform-origin:830px 470px;transform:([^\"]+)\" fill", block).group(1)
    if room_transform not in (None, t):
        sys.exit(f"room transform differs on stage {n}: {t}")
    room_transform = t
    ghosts = between('<g style="animation:{{ghostAnim}};transform-origin:830px 470px">', '</g><g style="animation:{{deckAnim}}', block)
    ghosts = ghosts.replace('<use href="#shellg"/>', ghost_shell)
    deck = between('<g class="roomg">', "</g></g>\n  </svg>", block)
    leaders = between('class="sceneIn" style="position:absolute;inset:0;overflow:visible;z-index:4;pointer-events:none" fill="none">', "</svg>", block)
    cards = [{"item": int(num) - 1, "top": int(top), "delay": float(d)} for top, d, num in card_re.findall(block)]
    rooms.append({"ghosts": ghosts, "room": deck, "leaders": leaders, "cards": cards})

blob = stars + defs + grid + ship + leads + json.dumps(rooms, ensure_ascii=False)
leftover = set(re.findall(r"\{\{[^}]+\}\}", blob))
if leftover:
    sys.exit(f"unresolved template vars: {leftover}")

out = Path(__file__).resolve().parent.parent / "client/src/scene/v2/markup.ts"
body = "// Generated by scripts/extract-v2.py from the CHANGES-2 Claude Design mockup. Do not edit by hand.\n"
for k, v in {"STARS": stars, "DEFS": defs, "GRID": grid, "SHIP": ship, "LEADS": leads, "ROOM_TRANSFORM": room_transform}.items():
    body += f"export const {k} = {json.dumps(v, ensure_ascii=False)};\n"
body += "export type RoomCard = { item: number; top: number; delay: number };\n"
body += "// Per stage 01–08: blurred ghost rooms, the room cutaway, leader lines, card order (sorted by anchor Y)\n"
body += "export const ROOMS: { ghosts: string; room: string; leaders: string; cards: RoomCard[] }[] = "
body += json.dumps(rooms, ensure_ascii=False, indent=1) + ";\n"
out.write_text(body, encoding="utf-8")
print(out, room_transform, [[c["item"] for c in r["cards"]] for r in rooms], {k: len(v) for k, v in {"defs": defs, "ship": ship, "rooms": json.dumps(rooms)}.items()})
